ROCK = (92, 88, 84)


def grid(text):
    rows = [r for r in text.strip('\n').split('\n')]
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), 'shape must be 16x16'
    return rows


def mix(a, b, t):
    return tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3))


def overlay(name, shape):
    hi, mid, lo = PALETTE[name]
    glint = mix(hi, (255, 255, 255), 0.55)
    rows = grid(shape)
    ore = {(x, y) for y, r in enumerate(rows) for x, c in enumerate(r) if c in '#*'}
    spark = {(x, y) for y, r in enumerate(rows) for x, c in enumerate(r) if c == '*'}
    rng = random.Random(f'overlay-{name}')
    img = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    px = img.load()
    shadow = mix(lo, (0, 0, 0), 0.55)
    for (x, y) in ore:
        up, left = (x, y - 1) in ore, (x - 1, y) in ore
        down, right = (x, y + 1) in ore, (x + 1, y) in ore
        if not down or not right:
            col = lo
        elif not up or not left:
            col = hi
        else:
            col = mid
            if rng.random() < GRAIN.get(name, 0.0):
                col = rng.choice((lo, hi)) if rng.random() < 0.5 else mix(mid, lo, 0.5)
        if (x, y) in spark:
            col = glint
        px[x, y] = col + (255,)
    for (x, y) in ore:  # drop shadow to the lower right, never over the ore itself
        for dx, dy in ((1, 0), (0, 1), (1, 1)):
            p = (x + dx, y + dy)
            if p not in ore and 0 <= p[0] < 16 and 0 <= p[1] < 16 and px[p][3] == 0:
                px[p] = shadow + (150,)
    return img


def centred(text):
    rows = [r.ljust(16, '.') for r in text.strip('\n').split('\n')]
    assert max(len(r) for r in rows) <= 16 and len(rows) <= 16, 'raw drawing too large'
    cells = {(x, y): c for y, r in enumerate(rows) for x, c in enumerate(r) if c != '.'}
    x0, x1 = min(x for x, _ in cells), max(x for x, _ in cells)
    y0, y1 = min(y for _, y in cells), max(y for _, y in cells)
    ox, oy = (16 - (x1 - x0 + 1)) // 2 - x0, (16 - (y1 - y0 + 1)) // 2 - y0
    return {(x + ox, y + oy): c for (x, y), c in cells.items()}


def raw(name):
    hi, mid, lo = PALETTE[name]
    glint = mix(hi, (255, 255, 255), 0.55)
    cells = centred(RAW[name])
    body = set(cells)
    metal = {p for p, c in cells.items() if c in 'm*'}
    rng = random.Random(f'raw-{name}')
    base = mix(ROCK, mid, 0.35)
    rock_hi, rock_mid, rock_lo = mix(base, (255, 255, 255), 0.12), base, mix(base, (0, 0, 0), 0.35)
    outline = mix(lo, (0, 0, 0), 0.6)
    img = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    px = img.load()
    for (x, y) in body:
        group = metal if (x, y) in metal else body - metal
        up, left = (x, y - 1) in group, (x - 1, y) in group
        down, right = (x, y + 1) in group, (x + 1, y) in group
        dark, lit = not down or not right, not up or not left
        if (x, y) in metal:
            col = lo if dark else (hi if lit else mid)
            if cells[(x, y)] == '*':
                col = glint
        else:
            col = rock_lo if dark else (rock_hi if lit else rock_mid)
            if not dark and rng.random() < 0.18:
                col = rock_lo
        px[x, y] = col + (255,)
    for (x, y) in body:
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            p = (x + dx, y + dy)
            if p not in body and 0 <= p[0] < 16 and 0 <= p[1] < 16:
                px[p] = outline + (255,)
    return img


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=TEX)
    ap.add_argument('ores', nargs='*')
    a = ap.parse_args()
    names = a.ores or sorted(SHAPES)
    for n in names:
        if n not in SHAPES:
            sys.exit(f'unknown ore: {n}')
        for sub in ('block', 'item'):
            os.makedirs(os.path.join(a.out, sub), exist_ok=True)
        overlay(n, SHAPES[n]).save(os.path.join(a.out, f'block/{n}_ore_overlay.png'))
        if n in RAW:
            raw(n).save(os.path.join(a.out, f'item/raw_{n}.png'))


if __name__ == '__main__':
    main()
